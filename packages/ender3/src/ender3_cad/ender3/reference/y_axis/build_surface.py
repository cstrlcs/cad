from build123d import Part, Pos, extrude

from ender3_cad.ender3.reference.construction import outline_face
from ender3_cad.ender3.reference.y_axis.dimensions import BED_CENTER_X, BED_CENTER_Y, BED_TOP_Z, BUILD_SURFACE_THICKNESS

BUILD_SURFACE_HALF_SIZE = 120.0
BUILD_SURFACE_TAB_HALF_WIDTH = 60.0
BUILD_SURFACE_TAB_TIP_HALF_WIDTH = 50.0
BUILD_SURFACE_TAB_TIP_Y = -135.0
BUILD_SURFACE_OUTLINE = [
    (-BUILD_SURFACE_HALF_SIZE, -BUILD_SURFACE_HALF_SIZE),
    (-BUILD_SURFACE_TAB_HALF_WIDTH, -BUILD_SURFACE_HALF_SIZE),
    (-BUILD_SURFACE_TAB_TIP_HALF_WIDTH, BUILD_SURFACE_TAB_TIP_Y),
    (BUILD_SURFACE_TAB_TIP_HALF_WIDTH, BUILD_SURFACE_TAB_TIP_Y),
    (BUILD_SURFACE_TAB_HALF_WIDTH, -BUILD_SURFACE_HALF_SIZE),
    (BUILD_SURFACE_HALF_SIZE, -BUILD_SURFACE_HALF_SIZE),
    (BUILD_SURFACE_HALF_SIZE, BUILD_SURFACE_HALF_SIZE),
    (-BUILD_SURFACE_HALF_SIZE, BUILD_SURFACE_HALF_SIZE),
]
BUILD_SURFACE_CORNER_RADIUS = 3.0
BUILD_SURFACE_TAB_CORNER_RADIUS = 2.0
BUILD_SURFACE_OUTLINE_RADII = [
    BUILD_SURFACE_CORNER_RADIUS,
    BUILD_SURFACE_TAB_CORNER_RADIUS,
    BUILD_SURFACE_TAB_CORNER_RADIUS,
    BUILD_SURFACE_TAB_CORNER_RADIUS,
    BUILD_SURFACE_TAB_CORNER_RADIUS,
    BUILD_SURFACE_CORNER_RADIUS,
    BUILD_SURFACE_CORNER_RADIUS,
    BUILD_SURFACE_CORNER_RADIUS,
]

BUILD_SURFACE_LOCATION = Pos(BED_CENTER_X, BED_CENTER_Y, BED_TOP_Z)


def build_surface() -> Part:
    outline = outline_face(BUILD_SURFACE_OUTLINE, BUILD_SURFACE_OUTLINE_RADII)
    surface = BUILD_SURFACE_LOCATION * extrude(outline, BUILD_SURFACE_THICKNESS)
    surface.label = "build_surface"
    return surface
