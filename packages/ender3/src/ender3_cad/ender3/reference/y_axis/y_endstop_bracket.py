from build123d import Part, Plane, Pos, Rectangle, RectangleRounded, extrude

from ender3_cad.ender3.reference.construction import circles

Y_ENDSTOP_BRACKET_SIZE = (20.0, 38.0)
Y_ENDSTOP_BRACKET_THICKNESS = 5.0
Y_ENDSTOP_BRACKET_CORNER_RADIUS = 1.5
Y_ENDSTOP_BRACKET_PROFILE_HOLE_DIAMETER = 4.7
Y_ENDSTOP_BRACKET_PROFILE_HOLE_OFFSETS = [(-6.0, -10.0), (6.0, -10.0)]
Y_ENDSTOP_BRACKET_SWITCH_HOLE_DIAMETER = 2.6
Y_ENDSTOP_BRACKET_SWITCH_HOLE_OFFSETS = [(6.05, -2.28704974), (6.05, 12.71295026)]
Y_ENDSTOP_BRACKET_SWITCH_BODY_WINDOW_CENTER = (-4.5, 6.66295026)
Y_ENDSTOP_BRACKET_SWITCH_BODY_WINDOW_SIZE = (7.1, 13.9)
Y_ENDSTOP_BRACKET_SWITCH_PIN_WINDOW_CENTER = (4.45, 5.06295026)
Y_ENDSTOP_BRACKET_SWITCH_PIN_WINDOW_SIZE = (3.0, 8.7)
Y_ENDSTOP_BRACKET_LOCATION = Pos(20.0, 115.0, 53.0)


def y_endstop_bracket() -> Part:
    outline = (
        RectangleRounded(*Y_ENDSTOP_BRACKET_SIZE, Y_ENDSTOP_BRACKET_CORNER_RADIUS)
        - circles(Y_ENDSTOP_BRACKET_PROFILE_HOLE_OFFSETS, Y_ENDSTOP_BRACKET_PROFILE_HOLE_DIAMETER)
        - circles(Y_ENDSTOP_BRACKET_SWITCH_HOLE_OFFSETS, Y_ENDSTOP_BRACKET_SWITCH_HOLE_DIAMETER)
        - Pos(*Y_ENDSTOP_BRACKET_SWITCH_BODY_WINDOW_CENTER) * Rectangle(*Y_ENDSTOP_BRACKET_SWITCH_BODY_WINDOW_SIZE)
        - Pos(*Y_ENDSTOP_BRACKET_SWITCH_PIN_WINDOW_CENTER) * Rectangle(*Y_ENDSTOP_BRACKET_SWITCH_PIN_WINDOW_SIZE)
    )
    bracket = Y_ENDSTOP_BRACKET_LOCATION * extrude(Plane.YZ * outline, Y_ENDSTOP_BRACKET_THICKNESS)
    bracket.label = "y_endstop_bracket"
    return bracket
