from build123d import Cylinder, Part, Pos, Rot, Torus

from ender3.dimensions import BOTTOM, FACE_FRONT, FACE_RIGHT
from ender3.ender3.reference.dimensions import CUT_THROUGH_LENGTH
from ender3.ender3.reference.extruder.dimensions import EXTRUDER_MOUNT_LOCATION

DRIVE_GEAR_BASE_Z = 5.52
DRIVE_GEAR_TEETH_DIAMETER = 10.95
DRIVE_GEAR_TEETH_HEIGHT = 7.0
DRIVE_GEAR_HUB_DIAMETER = 9.0
DRIVE_GEAR_HUB_HEIGHT = 3.9
DRIVE_GEAR_BORE_DIAMETER = 5.0
DRIVE_GEAR_GROOVE_Z = 3.5
DRIVE_GEAR_GROOVE_ROOT_DIAMETER = 10.0
DRIVE_GEAR_GROOVE_RADIUS = 2.5
DRIVE_GEAR_HOB_CUTTER_COUNT = 40
DRIVE_GEAR_HOB_CUTTER_DIAMETER = 3.4
DRIVE_GEAR_HOB_SLOT_WIDTH = 0.3
DRIVE_GEAR_HOB_CUTTER_AXIS_RADIUS = 6.3356
DRIVE_GEAR_HOB_CUTTER_START_ANGLE = 3.013
DRIVE_GEAR_SET_SCREW_DIAMETER = 2.5
DRIVE_GEAR_SET_SCREW_Z = 8.95
DRIVE_GEAR_SET_SCREWS = [(183.04, 0.738), (93.04, 0.0)]


def extruder_drive_gear() -> Part:
    gear = Cylinder(DRIVE_GEAR_TEETH_DIAMETER / 2, DRIVE_GEAR_TEETH_HEIGHT, align=BOTTOM)
    gear -= Pos(0, 0, DRIVE_GEAR_GROOVE_Z) * Torus(
        DRIVE_GEAR_GROOVE_ROOT_DIAMETER / 2 + DRIVE_GEAR_GROOVE_RADIUS,
        DRIVE_GEAR_GROOVE_RADIUS,
    )
    gear -= [
        Rot(
            0,
            0,
            DRIVE_GEAR_HOB_CUTTER_START_ANGLE + index * 360 / DRIVE_GEAR_HOB_CUTTER_COUNT,
        )
        * Pos(DRIVE_GEAR_HOB_CUTTER_AXIS_RADIUS, 0, DRIVE_GEAR_GROOVE_Z)
        * FACE_FRONT
        * Cylinder(DRIVE_GEAR_HOB_CUTTER_DIAMETER / 2, DRIVE_GEAR_HOB_SLOT_WIDTH)
        for index in range(DRIVE_GEAR_HOB_CUTTER_COUNT)
    ]
    gear += Pos(0, 0, DRIVE_GEAR_TEETH_HEIGHT) * Cylinder(
        DRIVE_GEAR_HUB_DIAMETER / 2, DRIVE_GEAR_HUB_HEIGHT, align=BOTTOM
    )
    gear -= Cylinder(DRIVE_GEAR_BORE_DIAMETER / 2, CUT_THROUGH_LENGTH)
    gear -= [
        Rot(0, 0, angle)
        * Pos(DRIVE_GEAR_HUB_DIAMETER / 2, offset, DRIVE_GEAR_SET_SCREW_Z)
        * FACE_RIGHT
        * Cylinder(DRIVE_GEAR_SET_SCREW_DIAMETER / 2, DRIVE_GEAR_HUB_DIAMETER)
        for angle, offset in DRIVE_GEAR_SET_SCREWS
    ]
    gear = EXTRUDER_MOUNT_LOCATION * Pos(0, 0, DRIVE_GEAR_BASE_Z) * gear
    gear.label = "extruder_drive_gear"
    return gear
