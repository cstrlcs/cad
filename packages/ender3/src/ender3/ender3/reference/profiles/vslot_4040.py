from build123d import Part, Polygon, extrude

from ender3.ender3.reference.profiles.construction import mirrored_quadrants, vslot_section
from ender3.ender3.reference.profiles.dimensions import (
    CELL_HALF_SIZE,
    INNER_POCKET_HALF_WIDTH,
    SLOT_BOTTOM_HALF_WIDTH,
    SLOT_CAVITY_HALF_WIDTH,
    SLOT_DEPTH,
    SLOT_GROOVE_HALF_WIDTH,
    SLOT_UNDERCUT_DEPTH,
)

VSLOT_4040_VOID_QUADRANT = [
    (CELL_HALF_SIZE + INNER_POCKET_HALF_WIDTH, SLOT_UNDERCUT_DEPTH),
    (CELL_HALF_SIZE + SLOT_CAVITY_HALF_WIDTH, SLOT_UNDERCUT_DEPTH),
    (CELL_HALF_SIZE + SLOT_BOTTOM_HALF_WIDTH, SLOT_DEPTH),
    (CELL_HALF_SIZE + SLOT_GROOVE_HALF_WIDTH, SLOT_DEPTH),
    (CELL_HALF_SIZE, SLOT_DEPTH + SLOT_GROOVE_HALF_WIDTH),
    (CELL_HALF_SIZE - SLOT_GROOVE_HALF_WIDTH, SLOT_DEPTH),
    (CELL_HALF_SIZE - SLOT_BOTTOM_HALF_WIDTH, SLOT_DEPTH),
    (SLOT_DEPTH, CELL_HALF_SIZE - SLOT_BOTTOM_HALF_WIDTH),
    (SLOT_DEPTH, CELL_HALF_SIZE - SLOT_GROOVE_HALF_WIDTH),
    (SLOT_DEPTH + SLOT_GROOVE_HALF_WIDTH, CELL_HALF_SIZE),
    (SLOT_DEPTH, CELL_HALF_SIZE + SLOT_GROOVE_HALF_WIDTH),
    (SLOT_DEPTH, CELL_HALF_SIZE + SLOT_BOTTOM_HALF_WIDTH),
    (SLOT_UNDERCUT_DEPTH, CELL_HALF_SIZE + SLOT_CAVITY_HALF_WIDTH),
]


def vslot_4040(length: float) -> Part:
    void = Polygon(*mirrored_quadrants(VSLOT_4040_VOID_QUADRANT))
    return extrude(vslot_section(2, 2, [void]), amount=length)
