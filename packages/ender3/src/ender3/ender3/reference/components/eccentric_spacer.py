from build123d import Cylinder, Part, Pos, RegularPolygon, extrude

from ender3.dimensions import BOTTOM

ECCENTRIC_SPACER_HEX_ACROSS_FLATS = 10.0
ECCENTRIC_SPACER_BOSS_DIAMETER = 7.2
ECCENTRIC_SPACER_BORE_DIAMETER = 5.0
ECCENTRIC_SPACER_ECCENTRICITY = 0.7
ECCENTRIC_SPACER_OFFSET_BOSS_HEIGHT = 0.5
ECCENTRIC_SPACER_HEX_TOP = 8.35
ECCENTRIC_SPACER_PLATE_BOSS_HEIGHT = 2.4
ECCENTRIC_SPACER_LENGTH = ECCENTRIC_SPACER_HEX_TOP + ECCENTRIC_SPACER_PLATE_BOSS_HEIGHT


def eccentric_spacer() -> Part:
    hex_height = ECCENTRIC_SPACER_HEX_TOP - ECCENTRIC_SPACER_OFFSET_BOSS_HEIGHT
    spacer = (
        Pos(0, ECCENTRIC_SPACER_ECCENTRICITY, 0)
        * Cylinder(ECCENTRIC_SPACER_BOSS_DIAMETER / 2, ECCENTRIC_SPACER_OFFSET_BOSS_HEIGHT, align=BOTTOM)
        + Pos(0, 0, ECCENTRIC_SPACER_OFFSET_BOSS_HEIGHT)
        * extrude(RegularPolygon(ECCENTRIC_SPACER_HEX_ACROSS_FLATS / 2, 6, major_radius=False), hex_height)
        + Pos(0, 0, ECCENTRIC_SPACER_HEX_TOP)
        * Cylinder(ECCENTRIC_SPACER_BOSS_DIAMETER / 2, ECCENTRIC_SPACER_PLATE_BOSS_HEIGHT, align=BOTTOM)
    )
    spacer -= Pos(0, ECCENTRIC_SPACER_ECCENTRICITY, 0) * Cylinder(
        ECCENTRIC_SPACER_BORE_DIAMETER / 2, ECCENTRIC_SPACER_LENGTH, align=BOTTOM
    )
    spacer.label = "eccentric_spacer"
    return spacer
