from math import sqrt

from build123d import Part, Plane, Polygon, Pos, extrude

from ender3.ender3.reference.profiles.dimensions import (
    SLOT_CAVITY_HALF_WIDTH,
    SLOT_DEPTH,
    SLOT_LIP_HALF_GAP,
    SLOT_LIP_THICKNESS,
    SLOT_OPENING_HALF_WIDTH,
    SLOT_UNDERCUT_DEPTH,
)
from ender3.upgrades.board_cases.dimensions import OUTER_WALL_GAP, RAIL_INNER_FACE_X, WALL_THICKNESS

RAIL_CLEARANCE = 0.3
RAIL_CLEARANCE_ACROSS_45_DEGREE_FACE = RAIL_CLEARANCE * sqrt(2)
RAIL_ROOT_DEPTH = -(OUTER_WALL_GAP + WALL_THICKNESS / 2)
RAIL_TIP_DEPTH = SLOT_DEPTH - RAIL_CLEARANCE
RAIL_NECK_HALF_WIDTH = SLOT_LIP_HALF_GAP - RAIL_CLEARANCE
RAIL_HOOK_START_DEPTH = SLOT_LIP_THICKNESS + RAIL_CLEARANCE
RAIL_HOOK_HALF_WIDTH = SLOT_CAVITY_HALF_WIDTH - RAIL_CLEARANCE
RAIL_V_FACE_OFFSET = SLOT_OPENING_HALF_WIDTH - RAIL_CLEARANCE_ACROSS_45_DEGREE_FACE
RAIL_TAPER_FACE_OFFSET = SLOT_CAVITY_HALF_WIDTH + SLOT_UNDERCUT_DEPTH - RAIL_CLEARANCE_ACROSS_45_DEGREE_FACE
RAIL_PROFILE = [
    (RAIL_ROOT_DEPTH, RAIL_V_FACE_OFFSET - RAIL_ROOT_DEPTH),
    (RAIL_TIP_DEPTH, RAIL_V_FACE_OFFSET - RAIL_TIP_DEPTH),
    (RAIL_TIP_DEPTH, RAIL_TIP_DEPTH - RAIL_TAPER_FACE_OFFSET),
    (RAIL_TAPER_FACE_OFFSET - RAIL_HOOK_HALF_WIDTH, -RAIL_HOOK_HALF_WIDTH),
    (RAIL_HOOK_START_DEPTH, -RAIL_HOOK_HALF_WIDTH),
    (RAIL_HOOK_START_DEPTH, -RAIL_NECK_HALF_WIDTH),
    (RAIL_V_FACE_OFFSET - RAIL_NECK_HALF_WIDTH, -RAIL_NECK_HALF_WIDTH),
    (RAIL_ROOT_DEPTH, RAIL_ROOT_DEPTH - RAIL_V_FACE_OFFSET),
]


def t_rail(slot_z: float, y_range: tuple[float, float]) -> Part:
    profile = Polygon(*[(RAIL_INNER_FACE_X + depth, slot_z + offset) for depth, offset in RAIL_PROFILE], align=None)
    return Pos(0, y_range[0], 0) * extrude(Plane.XZ * profile, y_range[1] - y_range[0], dir=(0, 1, 0))
